using System.Text;

namespace Mzm.Hilbert.Dsl;

public static class MeshIr
{
    public static string ToJson(MeshProgram p) => System.Text.Json.JsonSerializer.Serialize(p, new System.Text.Json.JsonSerializerOptions { WriteIndented = true });
}

public static class QSharpBackend
{
    public static string Emit(MeshProgram program)
    {
        var b = new StringBuilder();
        b.AppendLine("namespace QMesh.Generated {");
        b.AppendLine("    open Microsoft.Quantum.Intrinsic;");
        b.AppendLine("    open Microsoft.Quantum.Canon;");
        foreach (var block in program.QuantumBlocks)
        {
            b.AppendLine($"    operation {block.Name}() : Unit {{");
            foreach (var q in block.Qubits) b.AppendLine($"        use {q.Name} = Qubit();");
            foreach (var gate in block.Gates)
            {
                var args = string.Join(", ", gate.Qubits);
                b.AppendLine($"        {gate.Name}({args});");
            }
            foreach (var q in block.Qubits) b.AppendLine($"        Reset({q.Name});");
            b.AppendLine("    }");
        }
        b.AppendLine("}");
        return b.ToString();
    }
}

public static class QirBackend
{
    public static string Emit(MeshProgram p) => $"; QIR-compatible textual IR for {p.Name}\n; generated by qmeshc\n" +
        string.Join("\n", p.QuantumBlocks.SelectMany(b => b.Gates.Select(g => $"call @__quantum__qis__{g.Name.ToLowerInvariant()}__body(%{string.Join(", %", g.Qubits)});")));
}

public static class GraphvizBackend
{
    public static string Emit(MeshProgram p)
    {
        var b = new StringBuilder("digraph QMesh {\n");
        foreach (var block in p.QuantumBlocks)
        {
            foreach (var q in block.Qubits) b.AppendLine($"  \"{block.Name}.{q.Name}\" [shape=circle];");
            foreach (var gate in block.Gates)
                for (var i = 1; i < gate.Qubits.Count; i++) b.AppendLine($"  \"{block.Name}.{gate.Qubits[0]}\" -> \"{block.Name}.{gate.Qubits[i]}\" [label=\"{gate.Name}\"];");
        }
        return b.ToString() + "}\n";
    }
}

public static class YamlBackend
{
    public static string Emit(MeshProgram p) => $"mesh: {p.Name}\nquantumBlocks:\n" + string.Join("", p.QuantumBlocks.Select(b => $"  - name: {b.Name}\n    qubits: [{string.Join(", ", b.Qubits.Select(q => q.Name))}]\n    gates: [{string.Join(", ", b.Gates.Select(g => g.Name))}]\n"));
}
